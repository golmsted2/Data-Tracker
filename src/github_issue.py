"""Create the daily movement issue required by the tracker rubric."""

from __future__ import annotations

import json
import os
import re
from pathlib import Path
from urllib.request import Request, urlopen

try:
    from .pipeline import HISTORY_PATH, STATUS_PATH, movement_summary
except ImportError:
    from pipeline import HISTORY_PATH, STATUS_PATH, movement_summary


ISSUE_PREFIX = "Daily movement — "
API_ROOT = "https://api.github.com"


def github_request(method: str, path: str, token: str, payload: dict | None = None):
    body = json.dumps(payload).encode("utf-8") if payload is not None else None
    request = Request(
        f"{API_ROOT}{path}",
        data=body,
        method=method,
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "User-Agent": "ncaa-division-i-tracker/1.0",
            "X-GitHub-Api-Version": "2022-11-28",
        },
    )
    with urlopen(request, timeout=30) as response:
        return json.loads(response.read().decode("utf-8")) if response.readable() else None


def _format_pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def build_issue_body(history_rows: list[dict], status: dict, run_date: str) -> str:
    summary = movement_summary(history_rows)
    lines = [
        f"# Daily movement — {run_date}",
        "",
        f"Snapshot date: `{summary['current_date'] or 'none'}`  ",
        f"Previous snapshot: `{summary['previous_date'] or 'none'}`  ",
        f"Teams tracked: `{status.get('items', 0)}`  ",
        f"Games logged: `{status.get('games_logged', 0)}`",
        "",
        "## Biggest movers",
        "",
    ]
    if summary["movers"]:
        lines.extend([
            "| Team | Win % change | Point diff. change | Old → new point diff. |",
            "| --- | ---: | ---: | ---: |",
        ])
        for mover in summary["movers"]:
            win_change = mover["win_pct_delta"] * 100
            point_change = mover["point_diff_delta"]
            lines.append(
                f"| {mover['item']} | {win_change:+.1f} pts "
                f"({ _format_pct(mover['win_pct_old']) } → { _format_pct(mover['win_pct_new']) }) | "
                f"{point_change:+d} | {mover['point_diff_old']} → {mover['point_diff_new']} |"
            )
    else:
        lines.append("No tracked values changed from the previous available snapshot.")
    lines.extend(["", "## Appeared or disappeared", ""])
    lines.append(f"- Appeared: {', '.join(summary['appeared']) if summary['appeared'] else 'None'}")
    lines.append(f"- Disappeared: {', '.join(summary['disappeared']) if summary['disappeared'] else 'None'}")
    lines.extend(["", "## Source status", ""])
    for source in status.get("sources", []):
        lines.append(f"- `{source.get('name', 'Unknown source')}`: {'ok' if source.get('ok') else 'failed'} ({source.get('count', 0)} records)")
    if status.get("failed_dates"):
        lines.append(f"- Failed requested dates: `{', '.join(status['failed_dates'])}`")
    lines.extend([
        "",
        "Mover rule: compare the latest available snapshot with the previous available snapshot, ranking by absolute change in winning percentage and then absolute change in cumulative point differential.",
        "",
        "Generated by the daily GitHub Actions pipeline.",
    ])
    return "\n".join(lines)


def sync_issue(repository: str, token: str) -> dict:
    history_rows = []
    with HISTORY_PATH.open(encoding="utf-8", newline="") as handle:
        import csv

        history_rows = list(csv.DictReader(handle))
    status = json.loads(STATUS_PATH.read_text(encoding="utf-8"))
    run_date = (status.get("dates_requested") or [status.get("latest_date") or "unknown"])[-1]
    title = f"{ISSUE_PREFIX}{run_date}"
    body = build_issue_body(history_rows, status, run_date)
    issues = github_request("GET", f"/repos/{repository}/issues?state=open&per_page=100", token)
    current = next((issue for issue in issues if issue.get("title") == title), None)
    for issue in issues:
        if issue.get("number") != (current or {}).get("number") and re.match(r"^Daily movement — \d{4}-\d{2}-\d{2}$", issue.get("title", "")):
            github_request("PATCH", f"/repos/{repository}/issues/{issue['number']}", token, {"state": "closed"})
    if current:
        return github_request("PATCH", f"/repos/{repository}/issues/{current['number']}", token, {"title": title, "body": body, "state": "open"})
    return github_request("POST", f"/repos/{repository}/issues", token, {"title": title, "body": body})


def main() -> int:
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    repository = os.environ.get("GITHUB_REPOSITORY")
    if not token or not repository:
        raise SystemExit("GITHUB_TOKEN and GITHUB_REPOSITORY are required")
    issue = sync_issue(repository, token)
    print(f"Daily movement issue synchronized: {issue.get('html_url', issue.get('number', 'unknown'))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
